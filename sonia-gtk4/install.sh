#!/usr/bin/env bash
#
# install.sh — install (or remove) the native GTK4 client as a desktop app.
#
#   sonia-gtk4/install.sh              # per-user  (~/.local, no sudo)
#   sonia-gtk4/install.sh --system     # system-wide (/usr/local + /usr/share, sudo)
#   sonia-gtk4/install.sh --uninstall  # remove what was installed
#
# What gets installed (per-user layout):
#   ~/.local/bin/sonia-gtk4                          launcher (cd repo + bun run)
#   ~/.local/share/applications/sonia-gtk4.desktop   menu entry
#   ~/.local/share/icons/hicolor/256x256/apps/sonia-gtk4.png
#
# The launcher points at this checkout, so `git pull` in the repo updates the app
# with no reinstall. Set SONIA_GTK4_REPO at install time (or pass --repo) to
# install from somewhere else.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="${SONIA_GTK4_REPO:-$(cd "$SCRIPT_DIR/.." && pwd)}"
MODE="user"
ACTION="install"
APP_ID="sonia-gtk4"
DESKTOP_NAME="Sonia"
WM_CLASS="it.sonia.Assistant"

die() { printf 'install.sh: %s\n' "$*" >&2; exit 1; }
say() { printf '  %s\n' "$*"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --system) MODE="system"; shift ;;
    --user) MODE="user"; shift ;;
    --uninstall) ACTION="uninstall"; shift ;;
    --repo) REPO="$2"; shift 2 ;;
    -h|--help) sed -n '2,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done

# ── paths ─────────────────────────────────────────────────────────────────────
if [ "$MODE" = "system" ]; then
  BIN_DIR=/usr/local/bin
  APP_DIR=/usr/share/applications
  ICON_DIR=/usr/share/icons/hicolor/256x256/apps
  SUDO="sudo"
else
  BIN_DIR="$HOME/.local/bin"
  APP_DIR="$HOME/.local/share/applications"
  ICON_DIR="$HOME/.local/share/icons/hicolor/256x256/apps"
  SUDO=""
fi
LAUNCHER="$BIN_DIR/$APP_ID"
DESKTOP="$APP_DIR/$APP_ID.desktop"
ICON="$ICON_DIR/$APP_ID.png"
ICON_SRC_DIR="$SCRIPT_DIR/icons"
THEME_DIR=""   # hicolor/scalable/apps — only set when we ship custom glyphs

# ── uninstall ─────────────────────────────────────────────────────────────────
if [ "$ACTION" = "uninstall" ]; then
  echo "Removing $APP_ID ($MODE install)…"
  for f in "$LAUNCHER" "$DESKTOP" "$ICON"; do
    if [ -e "$f" ]; then
      $SUDO rm -f "$f" && say "removed $f"
    fi
  done
  if [ -d "$SCRIPT_DIR/icons" ]; then
    DEST_ICON_DIR="/usr/share/icons/hicolor/scalable/apps"
    [ "$MODE" = "user" ] && DEST_ICON_DIR="$HOME/.local/share/icons/hicolor/scalable/apps"
    for f in "$SCRIPT_DIR"/icons/*.svg; do
      [ -e "$f" ] || continue
      t="$DEST_ICON_DIR/$(basename "$f")"
      if [ -e "$t" ]; then $SUDO rm -f "$t" && say "removed $t"; fi
    done
  fi
  command -v update-desktop-database >/dev/null 2>&1 && \
    $SUDO update-desktop-database "$APP_DIR" 2>/dev/null || true
  $SUDO rmdir -p "$ICON_DIR" 2>/dev/null || true # only succeeds when empty
  echo "Done."
  exit 0
fi

# ── preflight ─────────────────────────────────────────────────────────────────
[ -f "$REPO/sonia-gtk4/main.ts" ] || die "sonia-gtk4/main.ts not found under '$REPO' (use --repo)"
command -v bun >/dev/null 2>&1 || die "bun not found in PATH"
BUN="$(command -v bun)"
say "repo:  $REPO"
say "bun:   $BUN"
say "mode:  $MODE"

if [ ! -d "$REPO/sonia-gtk4/node_modules/@sigmasd" ]; then
  say "installing jsGTK dependencies (bun install)…"
  (cd "$REPO/sonia-gtk4" && bun install >/dev/null) || die "bun install failed"
fi

mkdir -p "$BIN_DIR" "$APP_DIR" "$ICON_DIR" ${SUDO:+$SUDO true}

# ── launcher ──────────────────────────────────────────────────────────────────
# Written from a *quoted* heredoc (nothing expanded here) with the two paths
# substituted afterwards: an unquoted heredoc would expand the generated
# script's own $variables at install time — fatal under `set -u`.
esc_sed() { printf '%s' "$1" | sed -e 's/[\\&|]/\\&/g'; }

write_launcher() {
  local dest="$1" tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<'LAUNCHER_EOF'
#!/usr/bin/env bash
# sonia-gtk4 launcher - generated by sonia-gtk4/install.sh
# Native GTK4 client for the Sonia harness: talks the same /ws as the web UI.
set -euo pipefail
cd "@REPO@"
# Load the project .env, but never clobber what the caller already exported
# (HARNESS_URL, LOCALE, MIC_TARGET... must stay overridable).
if [ -f .env ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    key="${line%%=*}"
    key="${key//[[:space:]]/}"
    [ -n "${!key:-}" ] && continue
    export "$line"
  done < .env
fi
exec "@BUN@" run sonia-gtk4/main.ts "$@"
LAUNCHER_EOF
  sed -i -e "s|@REPO@|$(esc_sed "$REPO")|" -e "s|@BUN@|$(esc_sed "$BUN")|" "$tmp"
  bash -n "$tmp" || { rm -f "$tmp"; die "generated launcher is not valid bash"; }
  if [ -n "$SUDO" ]; then $SUDO install -Dm755 "$tmp" "$dest"; else install -Dm755 "$tmp" "$dest"; fi
  rm -f "$tmp"
  say "launcher  $dest"
}

write_launcher "$LAUNCHER"

# ── desktop entry ─────────────────────────────────────────────────────────────
tmp="$(mktemp)"
cat >"$tmp" <<EOF
[Desktop Entry]
Type=Application
Name=$DESKTOP_NAME (GTK)
GenericName=Assistente vocale
Comment=Client nativo GTK4 dell'assistente Sonia (stesso /ws della UI web)
Exec=$APP_ID
Icon=$APP_ID
Terminal=false
Categories=AudioVideo;Audio;
Keywords=voice;assistant;sonia;speech;llm;
StartupNotify=true
StartupWMClass=$WM_CLASS
EOF
if [ -n "$SUDO" ]; then $SUDO install -Dm644 "$tmp" "$DESKTOP"; else install -Dm644 "$tmp" "$DESKTOP"; fi
rm -f "$tmp"
say "desktop   $DESKTOP"

# ── icon ──────────────────────────────────────────────────────────────────────
SRC_ICON="$REPO/sonia.png"
if [ -f "$SRC_ICON" ]; then
  tmp="$(mktemp --suffix=.png)"
  if command -v magick >/dev/null 2>&1; then
    magick "$SRC_ICON" -resize 256x256 -background none -gravity center -extent 256x256 "$tmp"
  elif command -v convert >/dev/null 2>&1; then
    convert "$SRC_ICON" -resize 256x256 -background none -gravity center -extent 256x256 "$tmp"
  else
    cp "$SRC_ICON" "$tmp" # no ImageMagick: ship the original, desktops scale it
  fi
  if [ -n "$SUDO" ]; then $SUDO install -Dm644 "$tmp" "$ICON"; else install -Dm644 "$tmp" "$ICON"; fi
  rm -f "$tmp"
  say "icon      $ICON"
else
  say "icon      skipped (no sonia.png in the repo root)"
fi

# ── our own glyphs (send arrow, sweep broom) ────────────────────────────────
# GTK only finds them once they are in an icon theme directory, so they go into
# hicolor/scalable/apps; the app falls back to Adwaita if they are missing.
if [ -d "$ICON_SRC_DIR" ] && ls "$ICON_SRC_DIR"/*.svg >/dev/null 2>&1; then
  DEST_ICON_DIR="/usr/share/icons/hicolor/scalable/apps"
  [ "$MODE" = "user" ] && DEST_ICON_DIR="$HOME/.local/share/icons/hicolor/scalable/apps"
  mkdir -p ${SUDO:+$SUDO true} "$DEST_ICON_DIR"
  for f in "$ICON_SRC_DIR"/*.svg; do
    if [ -n "$SUDO" ]; then $SUDO install -Dm644 "$f" "$DEST_ICON_DIR/$(basename "$f")"; else install -Dm644 "$f" "$DEST_ICON_DIR/$(basename "$f")"; fi
    say "glyph     $(basename "$f")"
  done
  command -v gtk-update-icon-cache >/dev/null 2>&1 && $SUDO gtk-update-icon-cache -f -t "$DEST_ICON_DIR/.." >/dev/null 2>&1 || true
fi

command -v update-desktop-database >/dev/null 2>&1 && \
  $SUDO update-desktop-database "$APP_DIR" 2>/dev/null || true

echo
echo "Installed. Start it with:"
if [ "$MODE" = "user" ]; then
  echo "  ~/.local/bin/$APP_ID      (or 'bun run gtk4' from $REPO)"
else
  echo "  $LAUNCHER                 (or 'bun run gtk4' from $REPO)"
fi
echo "The harness must be running: bun run start   (bun run webui for the Chromium UI)"